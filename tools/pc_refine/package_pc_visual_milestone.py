def transport(source, output, label, kind, part_bytes=14_000_000):
    require(source.suffix.lower() == '.zip' and source.is_file(), 'Input must be completed canonical ZIP')
    require(re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9._-]+', source.name) and re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_-]+', label), 'Portable ASCII names required')
    new_dir(output); work = output / 'rebuild-files'; work.mkdir()
    before = sha(source); parts = []
    with source.open('rb') as stream:
        while body := stream.read(part_bytes):
            name = f'{source.name}.part{len(parts)+1:02d}'; (work / name).write_bytes(body)
            parts.append({'file': name, 'bytes': len(body), 'sha256': hashlib.sha256(body).hexdigest()})
    require(parts and before == sha(source), 'Canonical archive changed/empty')
    m = {'format': 1, 'file': source.name, 'bytes': source.stat().st_size, 'sha256': before, 'parts': parts,
         'artifact_kind': kind, 'all_parts_required': True, 'scope': 'Byte transport only, not game acceptance.'}
    mn = label + '-BINARY-PARTS.json'; write_json(work / mn, m); mh = sha(work / mn)
    stem = {'play': 'Rebuild-PC-Package', 'source': 'Rebuild-Source-Project', 'optional': 'Rebuild-Optional-Research'}[kind]
    py, ps = PYTHON_REBUILD, POWERSHELL_REBUILD
    for token, value in {'__MANIFEST__': mn, '__MANIFEST_HASH__': mh}.items(): py = py.replace(token, value); ps = ps.replace(token, value)
    (work / (stem + '.py')).write_text(py)
    (work / (stem + '.ps1')).write_text(ps, encoding='utf-8-sig')
    inline = '; '.join(line for line in ps.splitlines() if line.strip())
    cmd = ('@echo off\r\nsetlocal EnableExtensions DisableDelayedExpansion\r\n'
           'set "POOLCORE_REBUILD_BASE=%~dp0"\r\npowershell.exe -NoProfile -Command "' + inline + '"\r\n'
           'set "RESULT=%ERRORLEVEL%"\r\necho.\r\nif not "%RESULT%"=="0" echo Reconstruction failed. No partial final file was accepted.\r\npause\r\nexit /b %RESULT%\r\n')
    require(len(cmd.encode('ascii')) < 8000, 'CMD command exceeds portable limit')
    (work / (stem + '.cmd')).write_bytes(cmd.encode('ascii'))
    next_step = {'play': '解压重建得到的完整 ZIP，再使用 Launch-PoolCore.cmd。',
                 'source': '解压重建得到的完整 ZIP，再把完整 Godot EXE 拖到 Prepare-Editor.cmd。',
                 'optional': '仅需要旧实验/测试资料时，把重建 ZIP 内容解压到匹配的可编辑项目根目录。'}[kind]
    readme = label + '-RESTORE.txt'
    (work / readme).write_text(
        f'全部 {len(parts)} 个匹配 ZIP 解压到同一新文件夹；不能混用其他版本分块。\n'
        f'Windows 双击 {stem}.cmd；也可用 Python 3 运行 {stem}.py。\n'
        '校验 manifest、每个分块与最终 ZIP 的 SHA-256，不覆盖已存在的不同文件。\n'
        '不联网、不安装、不启动游戏、不修改安全策略。PowerShell 被限制时不要关闭保护，可用 Python。\n'
        + next_step + f'\n\nOutput: {source.name}\nSHA-256: {before}\n'
        'Binary chunks are not independent source/game packages. Extract every ZIP together, reconstruct, then extract the resulting complete ZIP.\n', encoding='utf-8-sig')
    common = [mn, readme] + [stem + ext for ext in ('.cmd', '.ps1', '.py')]
    archives = []
    for i, part in enumerate(parts, 1):
        target = output / f'{label}-Part{i:02d}-of-{len(parts):02d}.zip'
        with zipfile.ZipFile(target, 'x', zipfile.ZIP_DEFLATED, compresslevel=6) as z:
            for filename in [part['file'], *common]:
                info = zipfile.ZipInfo(filename, (2026, 1, 1, 0, 0, 0)); info.external_attr = 0o100644 << 16
                z.writestr(info, (work / filename).read_bytes(), compress_type=zipfile.ZIP_DEFLATED, compresslevel=6)
        require(target.stat().st_size < MAX_ATTACHMENT, 'Attachment too large')
        with zipfile.ZipFile(target) as z:
            require(z.testzip() is None, 'Transport ZIP CRC error')
            for filename in [part['file'], *common]:
                require(z.read(filename) == (work / filename).read_bytes(), 'Transport member differs')
        archives.append({'file': target.name, 'bytes': target.stat().st_size, 'sha256': sha(target)})
    # Exercise actual shipped Python scripts after extracting all supplied ZIPs.
    with tempfile.TemporaryDirectory(prefix='PoolCore 中文 paths ! ', dir=output.parent) as tmp:
        restored = Path(tmp)
        for row in archives:
            with zipfile.ZipFile(output / row['file']) as z: z.extractall(restored)
        # Existing different output is never replaced, even before part validation.
        existing = restored / source.name; existing.write_bytes(b'do not overwrite this file')
        run = subprocess.run([sys.executable, str(restored / (stem + '.py'))], capture_output=True, text=True)
        require(run.returncode != 0 and existing.read_bytes() == b'do not overwrite this file', 'Different existing output was not protected')
        existing.unlink()
        for attempt in range(2):
            run = subprocess.run([sys.executable, str(restored / (stem + '.py'))], capture_output=True, text=True)
            require(run.returncode == 0, 'Extracted Python reconstruction failed: ' + run.stderr)
        require(sha(restored / source.name) == before, 'Reconstruction hash mismatch')
        (restored / source.name).unlink()
        chunk = restored / parts[0]['file']; body = bytearray(chunk.read_bytes()); body[0] ^= 1; chunk.write_bytes(body)
        run = subprocess.run([sys.executable, str(restored / (stem + '.py'))], capture_output=True, text=True)
        require(run.returncode != 0 and not (restored / source.name).exists(), 'Corrupt part was not safely rejected')
        require(not list(restored.glob('.PoolCore-*.partial')), 'Failed reconstruction leaked a temporary file')
    result = {'status': 'PASS', 'kind': kind, 'input': m, 'archives': archives,
              'python_roundtrip_unicode_spaces_bang_path': True, 'idempotent_existing_output': True,
              'tampered_chunk_rejected': True, 'different_existing_output_preserved': True, 'windows_cmd_powershell_executed': False,
              'maximum_attachment_bytes_exclusive': MAX_ATTACHMENT, 'verification_limits': LIMITS}
    write_json(output / (label + '-DELIVERY.json'), result)
    return result



def runtime_name_allowed(name, cache):
    if name.startswith(('tools/', 'tests/', 'docs/', 'source_provenance/', 'output/', 'terrain-cache-history/')): return False
    if name.startswith(('assets/textures/pc_formal_plaster_candidate/', 'shaders/pc_gpu_cube/')): return False
    if name.startswith('scenes/lighting_lab/') and name not in {PREVIEW_SCENE, PREVIEW_SCENE + '.remap'}: return False
    if name.startswith('assets/lighting/') and not name.startswith(PREVIEW_PREFIX): return False
    if name.startswith('assets/cache/') and name.endswith('.terrain') and name not in cache: return False
    return True


def pck_audit(root, pack, package):
    pck = Pck(pack); require(pck.engine == '4.6.3', 'Milestone requires tested 4.6.3 PCK export')
    cache = current_cache(root); libraries, descriptor = check_registration(pck.read)
    require(descriptor == (root / 'native/source_water/source_water.gdextension').read_bytes(), 'Descriptor differs')
    dll = package / libraries['windows']
    require(dll.is_file() and dll.read_bytes() == (root / libraries['windows']).read_bytes(), 'External Windows DLL differs/missing')
    native = check_native_bytes(dll.read_bytes(), 'windows')
    require(libraries['windows'] not in pck.entries, 'Windows DLL must be beside pack at its relative descriptor path')
    for name in pck.entries:
        require(runtime_name_allowed(name, cache), 'Non-runtime/rejected/obsolete resource in PCK: ' + name)
    # No rejected import payload may hide behind an internal .godot path.
    for path in (root / 'assets').rglob('*.import'):
        name = path.relative_to(root).as_posix()
        if not runtime_name_allowed(name, cache):
            for target in re.findall(r'"res://([^"\n]+)"', path.read_text()):
                require(target not in pck.entries, 'Rejected candidate import leaked: ' + target)
    imports = []
    for name, data in pck.entries.items():
        if name.endswith(('.import', '.remap')):
            targets = re.findall(r'^path(?:\.[^=\n]+)?="res://([^"\n]+)"', data.decode('utf-8').rstrip('\0'), re.M)
            require(targets, 'Empty export remap: ' + name)
            for target in targets:
                safe_name(target); payload = pck.read(target); require(payload, 'Empty remap payload: ' + target)
                original = root / target
                require(original.is_file() and payload == original.read_bytes(), 'Export remap payload differs from frozen import: ' + target)
            imports.append({'resource': name, 'targets': targets})
    source_entries = inventory(root, scan=False)['files']
    checked = []
    for row in source_entries:
        name = row['path']; path = root / name
        if row['group'] != 'core' or not runtime_name_allowed(name, cache): continue
        raw = name.startswith('scripts/') and path.suffix == '.gd' or name.startswith('shaders/') and path.suffix in RAW_SUFFIXES or name in cache
        if raw:
            require(pck.read(name) == path.read_bytes(), 'Raw source/cache differs: ' + name); checked.append(name)
        if path.suffix == '.import' and name.startswith(('assets/', 'shaders/', 'scripts/mobile/')):
            require(name in pck.entries, 'Core runtime import missing: ' + name)
    for name in (PREVIEW_SCENE, PREVIEW_PREFIX + 'native_indirect.lmbake', PREVIEW_PREFIX + 'indirect_00.exr', 'scenes/main.tscn'):
        require(any(n in pck.entries for n in (name, name + '.remap', name + '.import')), 'Required resource missing: ' + name)
    literals = set()
    for row in source_entries:
        name = row['path']; path = root / name
        if row['group'] != 'core' or not name.startswith(('scripts/', 'shaders/', 'scenes/', 'assets/')) or path.suffix not in {'.gd', '.gdshader', '.gdshaderinc', '.tscn', '.tres'}: continue
        for ref in re.findall(r"[\"']res://([^\"'\n]+)[\"']", path.read_text()):
            if any(token in ref for token in ('%', '*')) or not Path(ref).suffix or ref.startswith('output/'): continue
            safe_name(ref)
            require(runtime_name_allowed(ref, cache), 'Runtime literal points to excluded resource: ' + name + ' -> ' + ref)
            require((root / ref).is_file(), 'Missing runtime literal source: ' + ref)
            require(any(n in pck.entries for n in (ref, ref + '.remap', ref + '.import')), 'PCK runtime literal absent: ' + ref)
            literals.add(ref)
    return {'status': 'PASS', 'kind': 'pc-visual-static-pck-audit', 'pck_sha256': sha(pack), 'bytes': pack.stat().st_size,
            'engine': pck.engine, 'entry_count': len(pck.entries), 'all_entry_md5_verified': True,
            'external_native': {'path': libraries['windows'], **native}, 'raw_source_cache_entries': checked,
            'imports': imports, 'preview_only_exception': [PREVIEW_SCENE, PREVIEW_PREFIX],
            'current_terrain_entries': len(cache), 'literal_dependencies_verified': sorted(literals), 'verification_limits': LIMITS}



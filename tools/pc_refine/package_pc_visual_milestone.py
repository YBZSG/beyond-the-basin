def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')


def new_dir(path):
    require(not path.exists(), f'Refusing existing output: {path}')
    path.mkdir(parents=True)


def scanned(path):
    # Scan all included bytes, including binary assets, without retaining matches.
    previous = b''
    with path.open('rb') as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b''):
            body = previous + chunk
            for name, expression in SECRET_PATTERNS:
                require(not expression.search(body), f'Potential {name} in {path.name}; review before packaging')
            previous = body[-512:]


def current_cache(root):
    report = json.loads((root / CACHE_MANIFEST).read_text())
    require(report.get('pass') is True and len(report.get('files', {})) == 16,
            'Current 16-file terrain manifest is required')
    for name, row in report['files'].items():
        safe_name(name)
        path = root / name
        require(name.startswith('assets/cache/source_terrain/') and name.endswith('.terrain'), 'Invalid terrain path')
        require(path.is_file() and not path.is_symlink() and path.stat().st_size == row['bytes']
                and sha(path) == row['sha256'], f'Current terrain mismatch: {name}')
    return report['files']


def classify(name, cache):
    p = Path(name); parts = p.parts
    if any(x.lower() in PRIVATE_DIRS or x.lower().startswith('blendcache_') for x in parts):
        return 'exclude', 'private directory, generated cache, toolchain or output'
    if p.suffix.lower() in IGNORE_SUFFIXES - {'.log'} or re.search(r'\.blend\d+$', name, re.I):
        return 'exclude', 'credential, generated bytecode or Blender backup/cache'
    if p.name == 'export_credentials.cfg' or p.name.startswith('.env'):
        return 'exclude', 'credential or environment file'
    if parts[:3] == ('native', 'source_water', 'build') or generated_fixture_path(parts):
        return 'exclude', 'generated native/fixture build workspace'
    if p.suffix in {'.translation', '.tar', '.gz', '.zip', '.apk', '.pck', '.exe', '.o', '.obj', '.lib'}:
        return 'exclude', 'historical generated archive, test binary or transient artifact'
    if parts[0] not in TOP_DIRS | {'terrain-cache-history'} and name not in ROOT_FILES:
        return 'exclude', 'root file outside explicit portable source allowlist'
    if name.startswith('terrain-cache-history/'):
        return 'exclude', 'duplicate obsolete cache history retained in earlier immutable delivery'
    if name.startswith('docs/verification/pc-refine/fine-water'):
        return 'exclude', 'pending finer-water follow-up QA, outside this frozen milestone'
    if name == 'CHECKPOINT-STATUS.md':
        return 'optional', 'historical checkpoint statement, not current acceptance'
    if name in CORE_EVIDENCE or name == PREVIEW_SCENE or name.startswith(PREVIEW_PREFIX):
        return 'core', 'current runtime/provenance dependency'
    if name.startswith('assets/cache/') and name.endswith('.terrain') and name not in cache:
        return 'optional', 'obsolete terrain snapshot, never current runtime identity'
    if name.startswith(('assets/lighting/', 'scenes/lighting_lab/')):
        return 'optional', 'non-runtime lighting research; no graphical acceptance'
    if name.startswith(OPTIONAL_PREFIXES) or p.suffix.lower() == '.log':
        return 'optional', 'historical QA, fixture, unused candidate or test log'
    return 'core', 'editable production source, model, generator, runtime asset or license'


def inventory(root, scan=True):
    require((root / 'project.godot').is_file(), 'Missing project.godot')
    cache = current_cache(root)
    check_editable_assets(root)
    config = configparser.ConfigParser(interpolation=None)
    config.read(root / 'export_presets.cfg')
    for section in config.sections():
        for key, value in config.items(section):
            if any(token in key for token in ('password', 'keystore/', 'codesign/identity')):
                require(not value.strip(chr(34)).strip(), 'Credential/signing value in export settings: ' + key)
    files, excluded = [], []
    for folder, dirs, names in os.walk(root, followlinks=False):
        folder = Path(folder)
        kept = []
        for name in sorted(dirs):
            path = folder / name; rel = path.relative_to(root).as_posix()
            if name.lower() in PRIVATE_DIRS or name.lower().startswith('blendcache_'):
                excluded.append({'path': rel + '/', 'reason': 'private/generated directory; not traversed'})
            else:
                require(not path.is_symlink(), f'Unclassified source directory symlink: {rel}')
                kept.append(name)
        dirs[:] = kept
        for name in sorted(names):
            path = folder / name; rel = path.relative_to(root).as_posix()
            group, reason = classify(rel, cache)
            if group == 'exclude':
                excluded.append({'path': rel, 'reason': reason}); continue
            require(not path.is_symlink() and path.is_file(), f'Non-regular source entry: {rel}')
            no_secrets([rel]); safe_name(rel)
            if scan: scanned(path)
            files.append({'path': rel, 'group': group, 'bytes': path.stat().st_size, 'sha256': sha(path), 'reason': reason})
    files.sort(key=lambda r: r['path']); excluded.sort(key=lambda r: r['path'])
    identity = hashlib.sha256(json.dumps(files, sort_keys=True, separators=(',', ':')).encode()).hexdigest()
    return {'format': 1, 'kind': 'pc-visual-source-inventory', 'status': 'INVENTORY_ONLY_NOT_FROZEN',
            'utc': datetime.now(timezone.utc).isoformat(), 'included_identity_sha256': identity,
            'groups': {g: {'files': sum(r['group'] == g for r in files),
                            'bytes': sum(r['bytes'] for r in files if r['group'] == g)} for g in ('core', 'optional')},
            'files': files, 'excluded': excluded, 'current_terrain_files': cache,
            'content_secret_scan': {'status': 'PASS', 'patterns': [r[0] for r in SECRET_PATTERNS],
                                    'all_included_bytes_scanned': scan},
            'verification_limits': LIMITS}


def check_inventory(root, expected):
    actual = inventory(root, scan=False)
    require(expected['content_secret_scan']['all_included_bytes_scanned'] is True, 'Inventory requires complete original content scan')
    require(actual['included_identity_sha256'] == expected['included_identity_sha256'],
            'Included source file set/bytes changed; make a new freeze inventory, not a patched manifest')
    return actual


def archive_tree(root, target):
    require(not target.exists(), 'Archive destination already exists')
    target.parent.mkdir(parents=True, exist_ok=True)
    expected = {p.relative_to(root).as_posix(): p for p in root.rglob('*') if p.is_file()}
    no_secrets(expected)
    with zipfile.ZipFile(target, 'x', zipfile.ZIP_DEFLATED, compresslevel=6) as z:
        for rel, path in sorted(expected.items()):
            require(not path.is_symlink(), f'Archive symlink: {rel}')
            info = zipfile.ZipInfo(rel, (2026, 1, 1, 0, 0, 0)); info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = (0o100755 if path.stat().st_mode & 0o111 else 0o100644) << 16
            with path.open('rb') as src, z.open(info, 'w') as dst:
                shutil.copyfileobj(src, dst, 1024 * 1024)
    with zipfile.ZipFile(target) as z:
        require(z.testzip() is None and set(z.namelist()) == set(expected), 'ZIP CRC or file-set mismatch')
        for rel, path in expected.items():
            h = hashlib.sha256()
            with z.open(rel) as stream:
                for b in iter(lambda: stream.read(1024 * 1024), b''): h.update(b)
            require(h.hexdigest() == sha(path), f'ZIP member hash mismatch: {rel}')
    return {'file': target.name, 'bytes': target.stat().st_size, 'sha256': sha(target), 'files': len(expected)}



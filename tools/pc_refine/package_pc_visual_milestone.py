def audit_launcher(data, preview=False):
    text = data.decode('ascii')
    for expected in ('DisableDelayedExpansion', 'set "ENGINE=%~f1"', '"%RUNEXE%" --rendering-method forward_plus',
                     'Get-FileHash -LiteralPath', '[System.IO.FileMode]::CreateNew',
                     '--log-file "%GODOTLOG%"', 'pause', ':engine_copy_failed'):
        require(expected in text, 'Missing launcher contract: ' + expected)
    require(text.index('set "ENGINE=%~f1"') < text.index('pushd'), 'Relative engine path resolved too late')
    require((PREVIEW_FLAG in text) == preview and b'\r\n' in data, 'Wrong mode/line endings')
    commands = [line for line in text.splitlines() if line.startswith('"%RUNEXE%"')]
    require(len(commands) == 1 and not any(flag in commands[0] for flag in ('--path', '--main-pack', '--script')), 'Restricted CLI override used')
    require('ExecutionPolicy' not in text and 'curl ' not in text, 'Unexpected policy/network command')
    return {'static_contract': 'PASS', 'windows_cmd_executed': False, 'mode': 'preview' if preview else 'normal',
            'engine_copy_create_new_only': True, 'engine_copy_sha256_required': True, 'normal_sibling_pck_discovery': True}


def freeze_private(root, out):
    """Private build snapshot only. Mutable/new optional QA is explicitly omitted."""
    expected = inventory(root); new_dir(out)
    omitted = []
    for row in expected['files']:
        path = root / row['path']; target = out / row['path']
        if not path.is_file() or sha(path) != row['sha256']:
            require(row['group'] == 'optional', 'Production file changed before freeze: ' + row['path'])
            omitted.append({'path': row['path'], 'reason': 'Optional report changed during source freeze'}); continue
        target.parent.mkdir(parents=True, exist_ok=True); shutil.copy2(path, target)
        if sha(target) != row['sha256'] or sha(path) != row['sha256']:
            require(row['group'] == 'optional', 'Production file changed during freeze: ' + row['path'])
            target.unlink(); omitted.append({'path': row['path'], 'reason': 'Optional report changed during source copy'})
    # Imports are retained privately to make source/actual-PCK payload checks exact.
    imports = root / '.godot/imported'
    require(imports.is_dir() and not imports.is_symlink(), 'Completed import cache is required')
    private = sorted(p for p in imports.rglob('*') if p.is_file())
    private += [root / '.godot' / n for n in ('extension_list.cfg', 'global_script_class_cache.cfg', 'uid_cache.bin', '.gdignore') if (root / '.godot' / n).is_file()]
    for name in ('extension_list.cfg', 'global_script_class_cache.cfg', 'uid_cache.bin'):
        require((root / '.godot' / name).is_file(), 'Required build registry missing: ' + name)
    private_rows = []
    for path in private:
        require(not path.is_symlink(), 'Private import symlink refused')
        rel = path.relative_to(root).as_posix(); no_secrets([rel]); before = sha(path)
        target = out / rel; target.parent.mkdir(parents=True, exist_ok=True); shutil.copy2(path, target)
        require(before == sha(target) == sha(path), 'Imported build payload changed: ' + rel)
        private_rows.append({'path': rel, 'bytes': target.stat().st_size, 'sha256': before})
    after = inventory(root)
    core_before = [r for r in expected['files'] if r['group'] == 'core']
    core_after = [r for r in after['files'] if r['group'] == 'core']
    require(core_before == core_after, 'Production source file set/bytes changed during freeze')
    frozen = inventory(out)
    require([r for r in frozen['files'] if r['group'] == 'core'] == core_before, 'Frozen core file set differs')
    source_names = {r['path'] for r in expected['files']}
    new_optional = [r['path'] for r in after['files'] if r['group'] == 'optional' and r['path'] not in source_names]
    write_json(out / 'FROZEN-SOURCE-INVENTORY.json', frozen)
    (out / 'PRIVATE-BUILD-NOT-FOR-DELIVERY.txt').write_text(
        'PRIVATE BUILD INPUTS. NEVER SHIP THIS DIRECTORY OR ITS .godot CONTENTS.\n'
        'Use stage-source to create clean editable source from this frozen project.\n'
        'Pending fine-water QA and new optional reports written during freeze are not part of this milestone.\n'
        'No engine import, export, GPU render, bake, Android action or signing occurred during this copy.\n')
    result = {'status': 'PASS', 'kind': 'private-pc-visual-build-freeze', 'distributable': False,
              'source_inventory_sha256': frozen['included_identity_sha256'], 'source_groups': frozen['groups'],
              'private_import_files': private_rows, 'private_import_bytes': sum(r['bytes'] for r in private_rows),
              'omitted_changed_optional_reports': omitted, 'omitted_new_optional_reports': new_optional,
              'excluded_source_paths': expected['excluded'], 'verification_limits': LIMITS}
    write_json(out / 'BUILD-FREEZE-RECEIPT.json', result)
    manifest(out, 'private-pc-visual-build-inputs-not-distributable', result, prefix='BUILD-')
    verify_manifest(out, prefix='BUILD-')
    return {k: v for k, v in result.items() if k not in ('private_import_files', 'excluded_source_paths')}



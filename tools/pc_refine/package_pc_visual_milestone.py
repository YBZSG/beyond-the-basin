def main():
    parser = argparse.ArgumentParser(description=__doc__); sub = parser.add_subparsers(dest='action', required=True)
    p = sub.add_parser('inventory'); p.add_argument('--source', type=Path, required=True); p.add_argument('--report', type=Path, required=True)
    p = sub.add_parser('freeze'); p.add_argument('--source', type=Path, required=True); p.add_argument('--output', type=Path, required=True); p.add_argument('--freeze-confirmed', action='store_true', required=True)
    for command in ('stage-source', 'stage-play'):
        p = sub.add_parser(command); p.add_argument('--source', type=Path, required=True); p.add_argument('--output', type=Path, required=True)
        p.add_argument('--inventory', type=Path, required=True); p.add_argument('--freeze-confirmed', action='store_true', required=True)
        if command == 'stage-play': p.add_argument('--pck', type=Path, required=True); p.add_argument('--validation-receipt', type=Path, required=True)
    p = sub.add_parser('audit-pck'); p.add_argument('--source', type=Path, required=True); p.add_argument('--pck', type=Path, required=True); p.add_argument('--package-root', type=Path, required=True); p.add_argument('--report', type=Path, required=True)
    p = sub.add_parser('archive'); p.add_argument('--directory', type=Path, required=True); p.add_argument('--output', type=Path, required=True)
    p = sub.add_parser('transport'); p.add_argument('--input', type=Path, required=True); p.add_argument('--output', type=Path, required=True); p.add_argument('--label', required=True); p.add_argument('--kind', choices=('play', 'source', 'optional'), required=True)
    p = sub.add_parser('selftest'); p.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    try:
        if hasattr(args, 'source'): args.source = args.source.resolve()
        if args.action == 'inventory':
            result = inventory(args.source); require(not args.report.exists(), 'Inventory output exists'); write_json(args.report, result)
        elif args.action == 'freeze':
            require(args.source != args.output.resolve() and args.source not in args.output.resolve().parents, 'Freeze outside source tree')
            result = freeze_private(args.source, args.output.resolve())
        elif args.action in ('stage-source', 'stage-play'):
            expected = json.loads(args.inventory.read_text())
            require(args.source != args.output.resolve() and args.source not in args.output.resolve().parents, 'Stage outside source tree')
            if args.action == 'stage-source': result = source_stage(args.source, args.output, expected)
            else: result = play_stage(args.source, args.pck, args.output, expected, args.validation_receipt)
        elif args.action == 'audit-pck':
            result = pck_audit(args.source, args.pck, args.package_root); require(not args.report.exists(), 'Audit report already exists'); write_json(args.report, result)
        elif args.action == 'archive': verify_manifest(args.directory); result = archive_tree(args.directory, args.output); verify_manifest(args.directory)
        elif args.action == 'transport': result = transport(args.input.resolve(), args.output.resolve(), args.label, args.kind)
        else: result = selftest(args.output.resolve())
        if args.action == 'inventory': print(json.dumps({k: result[k] for k in ('status', 'groups', 'included_identity_sha256', 'content_secret_scan')}, indent=2))
        else: print(json.dumps(result, ensure_ascii=False, indent=2))
        return 0
    except (AuditError, OSError, ValueError, KeyError, zipfile.BadZipFile) as exc:
        print('PC_MILESTONE_PACKAGING_FAIL: ' + str(exc) + '\nPartial output is not a delivery.', file=sys.stderr); return 1


if __name__ == '__main__': sys.exit(main())
